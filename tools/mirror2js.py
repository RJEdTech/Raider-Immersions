#!/usr/bin/env python3
"""Turn the private Denver_Shared_Mirror.md into trips/denver-mirror.js (public: red-marked items dropped)."""
import json, re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from packet2js import clean, drop_red, mark_of, strip_marks, RED
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def main(path):
    md = open(path, encoding='utf-8').read()
    out = {}
    for sec in re.split(r'^## ', md, flags=re.M)[1:]:
        head, _, body = sec.partition('\n')
        m = re.match(r'(D-[A-Z]+) · (.*)', head)
        if not m:
            continue
        key, title = m.group(1), re.sub(r'\s*\*\(.*?\)\*', '', m.group(2)).strip()
        k = {'key': key, 'title': title, 'figures': [], 'misses': [], 'sources': []}
        cur = None
        for line in body.split('\n'):
            bm = re.match(r'^\*\*([^*]+?)\.?\*\*\s*(.*)', line)
            if bm:
                h = bm.group(1).lower(); rest = bm.group(2)
                if h.startswith('plain'): k['plain'] = drop_red(clean(rest)); cur = None
                elif h.startswith('mechanism'): k['how'] = drop_red(clean(rest)); cur = 'how'
                elif h.startswith('figure'): cur = 'figures'; rest and RED not in rest and k['figures'].append({'text': strip_marks(clean(rest)), 'mark': mark_of(rest)})
                elif h.startswith('who'): cur = 'misses'; rest and k['misses'].append(drop_red(clean(rest)))
                elif h.startswith('mirror question'): k['mirrorQ'] = clean(rest).strip('*'); cur = None
                else: cur = None
                continue
            if line.startswith('Sources:'):
                k['sources'] = [u.rstrip('.,)') for u in re.findall(r'https?://\S+', line)]; cur = None; continue
            li = re.match(r'^(?:- |\d+\. )(.*)', line)
            if li and cur and RED not in li.group(1):
                t = clean(li.group(1))
                if cur == 'figures': k['figures'].append({'text': strip_marks(t), 'mark': mark_of(t)})
                elif cur == 'misses': k['misses'].append(strip_marks(t))
                elif cur == 'how': k['how'] = (k.get('how', '') + ' ' + strip_marks(t)).strip()
            elif li and cur and RED in li.group(1) and cur in ('figures', 'misses'):
                t = drop_red(clean(li.group(1)))
                if t: (k['figures'] if cur == 'figures' else k['misses']).append({'text': strip_marks(t), 'mark': mark_of(t)} if cur == 'figures' else strip_marks(t))
        out[key] = k
    js = '/* Generated by tools/mirror2js.py from the private Denver mirror. Do not edit by hand. */\nwindow.DMIRROR=' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
    open(os.path.join(ROOT, 'trips', 'denver-mirror.js'), 'w', encoding='utf-8').write(js)
    print('keys:', len(out))

if __name__ == '__main__':
    main(sys.argv[1])
